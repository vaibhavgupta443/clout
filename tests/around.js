// Around town: the second tab of Explore, with communities, what is happening, rumours, and a box to answer.
const { boot } = require('./harness');
const root = process.argv[2] || require('path').resolve(__dirname, '..');
const H = boot(root);
const { w, G, E, check } = H;
const $ = (s) => w.document.querySelector(s);
const $$ = (s) => Array.from(w.document.querySelectorAll(s));
(async () => {
  w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
  await H.wait(100);
  H.freshWorld();
  w.document.body.classList.add('ingame');
  G.settings.legacyHome = false; G.settings.minimalUI = true;
  let S = G.S;
  const mia = Object.values(S.npcs).find((n) => n.name === 'Mia Vale');
  const kai = Object.values(S.npcs).find((n) => n.name === 'Kai Storm');
  G.Channels.ensure();
  const [c1, c2] = [S.channels.find((c) => c.id === 'town-talk'), S.channels.find((c) => c.id === 'the-drama')];
  c1.msgs.push({ id: 'a1', from: mia.id, text: 'did anyone see the lighthouse light last night', t: S.clock - 30 });
  c2.msgs.push({ id: 'a2', from: kai.id, text: 'some people never answer their messages', t: S.clock - 10 });
  E.addChron('Kai and Mia fought outside the studio');
  S.storylines.push({ id: 's9', title: 'Who leaked the demo tape', summary: 'x', heat: 70, status: 'active', participants: [mia.id], updated: S.clock, log: [] });
  const ru = G.World.startRumor('Sam is leaving the label', 'me', [mia.id], false); ru.belief[mia.id] = 0.7;
  G.UI.exTab = 'explore'; G.UI.go('explore'); G.UI.render();
  check('Explore has two tabs: Explore | Around town', $$('.seg button').length === 2 && /Around town/.test($('.seg').textContent));
  $('.seg button[data-t="around"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  check('tapping Around town switches to it', G.UI.exTab === 'around' && !!$('.comms'));
  check('the communities are a single scrolling row, with All first', $$('.comm').length >= 6 && /^All/.test($$('.comm')[0].textContent) && /Town talk/.test($('.comms').textContent) && /The drama/.test($('.comms').textContent));
  const page = $('#page').textContent;
  check('All shows what is happening, the rumours and what people say', /Who leaked the demo tape/.test(page) && /fought outside the studio/.test(page) && /Sam is leaving the label/.test(page) && /lighthouse light/.test(page) && /some people never answer/.test(page));
  check('newest first across communities', page.indexOf('some people never answer') < page.indexOf('lighthouse light'));
  $('.comm[data-id="the-drama"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  const p2 = $('#page').textContent;
  check('a community shows only its own messages', /some people never answer/.test(p2) && !/lighthouse light/.test(p2) && !/fought outside the studio/.test(p2));
  $('#ar_text').value = 'I have something to say about this';
  $('[data-act="arSend"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  S = G.S;
  check('answering posts into that community (and people may answer back)', S.channels.find((c) => c.id === 'the-drama').msgs.some((m) => m.from === 'me' && /something to say/.test(m.text)) && /something to say/.test($('#page').textContent));
  $('.comm[data-id="all"]').dispatchEvent(new w.MouseEvent('click', { bubbles: true }));
  G.UI.go('notifs'); G.UI.render();
  check('the Alerts page no longer carries the around-town strip', !$('.townstrip'));
  G.UI.exTab = 'explore'; G.UI.go('explore'); G.UI.render();
  check('the Explore tab is unchanged underneath', !!$('.seg button.on[data-t="explore"]') && !!$('.gtile, .search, input'));
  H.summary('AROUND TOWN');
  process.exit(process.exitCode || 0);
})().catch((e) => { console.log('CRASH', (e && e.stack) || e); process.exit(2); });
